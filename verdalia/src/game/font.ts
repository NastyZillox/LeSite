export const CHAR_W = 6
export const CHAR_H = 8

export function measure(text: string, scale = 1): number {
  return text.length * CHAR_W * scale
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color = '#f8f8f8',
  scale = 1,
  shadow = true,
) {
  if (shadow) drawTextRaw(ctx, text, x + scale, y + scale, '#203038', scale)
  drawTextRaw(ctx, text, x, y, color, scale)
}

function drawTextRaw(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale: number,
) {
  ctx.fillStyle = color
  let cx = x
  for (const ch of text) {
    const g = G[ch] ?? G['?']
    for (let row = 0; row < 7; row++) {
      const bits = g[row] ?? 0
      for (let col = 0; col < 5; col++) {
        if (bits & (1 << (4 - col))) {
          ctx.fillRect(cx + col * scale, y + row * scale, scale, scale)
        }
      }
    }
    cx += CHAR_W * scale
  }
}

export function wrapText(text: string, maxChars: number): string[] {
  const out: string[] = []
  for (const raw of text.split('\n')) {
    const words = raw.split(' ')
    let line = ''
    for (const w of words) {
      const next = line ? `${line} ${w}` : w
      if (next.length <= maxChars) line = next
      else {
        if (line) out.push(line)
        if (w.length > maxChars) {
          for (let i = 0; i < w.length; i += maxChars) out.push(w.slice(i, i + maxChars))
          line = ''
        } else line = w
      }
    }
    if (line) out.push(line)
  }
  return out.length ? out : ['']
}
